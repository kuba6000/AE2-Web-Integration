/** Each theme registers its dictionaries independently of the shared messages. */
export function createI18n() {
    const dictionaries: Dictionaries = {};
    return {
        register(additions: Dictionaries) {
            for (const [language, messages] of Object.entries(additions)) {
                Object.defineProperty(dictionaries, language, {
                    value: { ...(Object.hasOwn(dictionaries, language) ? dictionaries[language] : {}), ...messages },
                    configurable: true,
                    enumerable: true,
                    writable: true
                });
            }
        },
        forLanguage(language: string) {
            return createTranslator(language, dictionaries);
        }
    };
}

function createTranslator(language: string, dictionaries: Dictionaries) {
    const numbers = new Intl.NumberFormat(language);
    const byteNumbers = new Intl.NumberFormat(language, { maximumFractionDigits: 2 });
    const plural = new Intl.PluralRules(language);
    const englishPlural = new Intl.PluralRules('en');
    const times = new Intl.DateTimeFormat(language, { timeStyle: 'medium', hourCycle: 'h23' });
    const dates = new Intl.DateTimeFormat(language, {
        dateStyle: 'medium',
        timeStyle: 'medium',
        hourCycle: 'h23'
    });
    function translate(source: Dictionaries, key: string, values: MessageValues) {
        const selected = Object.hasOwn(source, language) ? source[language] : {};
        const english = Object.hasOwn(source, 'en') ? source.en : {};
        const localized = Object.hasOwn(selected, key);
        let message = localized ? selected[key] : Object.hasOwn(english, key) ? english[key] : key;
        if (typeof message === 'object') {
            const form = (localized ? plural : englishPlural).select(values.count ?? NaN);
            message = Object.hasOwn(message, form) ? (message[form] ?? message.other) : message.other;
        }
        return message.replace(/\{(\w+)\}/g, (_, name) =>
            typeof values[name] === 'number' ? numbers.format(values[name]) : String(values[name] ?? '')
        );
    }
    return {
        t: (key: string, values: MessageValues = {}) => translate(dictionaries, key, values),
        common: (key: string, values: MessageValues = {}) => translate(translations, key, values),
        duration(milliseconds: number) {
            let remaining = Math.max(0, milliseconds);
            if (remaining >= 60000) remaining = Math.floor(remaining / 1000) * 1000;
            const parts: string[] = [];
            for (const [unit, size] of [
                ['durationDays', 86400000],
                ['durationHours', 3600000],
                ['durationMinutes', 60000]
            ] as const) {
                const count = Math.floor(remaining / size);
                remaining %= size;
                if (count) parts.push(translate(translations, unit, { count }));
            }
            if (remaining || !parts.length)
                parts.push(translate(translations, 'durationSeconds', { count: remaining / 1000 }));
            return parts.join(' ');
        },
        number: (value: number) => numbers.format(value),
        bytes(value: number) {
            // AE2 uses binary steps with KB/MB labels, independently of item-count abbreviations.
            const units = ['B', 'KB', 'MB', 'GB', 'TB', 'PB', 'EB'];
            let unit = 0;
            while (value >= 1024 && unit < units.length - 1) {
                value /= 1024;
                unit++;
            }
            return `${byteNumbers.format(value)} ${units[unit]}`;
        },
        time: (value: number) => times.format(value),
        dateTime(value: number, reference?: number) {
            if (reference !== undefined) {
                const date = new Date(value);
                const referenceDate = new Date(reference);
                if (
                    date.getFullYear() === referenceDate.getFullYear() &&
                    date.getMonth() === referenceDate.getMonth() &&
                    date.getDate() === referenceDate.getDate()
                )
                    return times.format(value);
            }
            return dates.format(value);
        }
    };
}
