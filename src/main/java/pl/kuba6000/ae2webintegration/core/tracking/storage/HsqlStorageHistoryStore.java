package pl.kuba6000.ae2webintegration.core.tracking.storage;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Types;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.Properties;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.TimeUnit;

import org.hsqldb.jdbc.JDBCDriver;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import pl.kuba6000.ae2webintegration.core.api.ResourceType;
import pl.kuba6000.ae2webintegration.core.identity.StableKey;
import pl.kuba6000.ae2webintegration.core.tracking.ResourceSnapshot;

/** Disk-backed typed history. All JDBC work belongs to detached worker/request threads. */
public final class HsqlStorageHistoryStore implements IStorageHistoryStore {

    private static final String EXPIRED_POINTS = "p.observed_at<? AND (p.kind<>'STOCK' OR p.item_key IS NULL OR EXISTS (SELECT 1 FROM history_points newer WHERE newer.grid_id=p.grid_id AND newer.item_key=p.item_key AND newer.kind='STOCK' AND newer.observed_at<? AND (newer.observed_at>p.observed_at OR newer.observed_at=p.observed_at AND newer.id>p.id)))";
    private static final long MAINTENANCE_INTERVAL_MILLIS = TimeUnit.MINUTES.toMillis(1);
    private static final Set<Path> OPEN_DATABASES = ConcurrentHashMap.newKeySet();

    private final Path databaseBase;
    private final int retentionDays;
    private final int maxRowsPerGrid;
    private @Nullable Connection connection;
    private @Nullable Path ownedPath;
    private boolean closed;
    private long nextMaintenance;

    public HsqlStorageHistoryStore(@NotNull Path databaseBase, int retentionDays, int maxRowsPerGrid) {
        if (retentionDays < 1 || maxRowsPerGrid < 1)
            throw new IllegalArgumentException("History limits must be positive");
        if (databaseBase.toString()
            .indexOf(';') >= 0)
            throw new IllegalArgumentException("History path cannot contain JDBC property separators");
        this.databaseBase = databaseBase.toAbsolutePath();
        this.retentionDays = retentionDays;
        this.maxRowsPerGrid = maxRowsPerGrid;
    }

    private Connection database() throws SQLException, IOException {
        if (closed) throw new IOException("History store is closed");
        if (connection != null) return connection;
        Files.createDirectories(databaseBase.getParent());
        Path canonical = databaseBase.getParent()
            .toRealPath()
            .resolve(databaseBase.getFileName());
        if (!OPEN_DATABASES.add(canonical))
            throw new IOException("Storage history database is still owned by an active service");
        ownedPath = canonical;
        Properties properties = new Properties();
        properties.setProperty("user", "SA");
        properties.setProperty("password", "");
        Connection opened;
        try {
            opened = new JDBCDriver().connect(
                "jdbc:hsqldb:file:" + canonical.toString()
                    .replace('\\', '/'),
                properties);
        } catch (SQLException failedConnection) {
            releaseOwnership();
            throw failedConnection;
        }
        try {
            try (Statement sql = opened.createStatement()) {
                sql.execute("SET FILES WRITE DELAY FALSE");
                sql.execute("SET FILES CACHE SIZE 16384");
                sql.execute("SET FILES LOG SIZE 16");
                sql.execute("SET FILES DEFRAG 25");
                sql.execute(
                    "CREATE CACHED TABLE IF NOT EXISTS history_grids (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, grid_key VARCHAR(22) NOT NULL UNIQUE, row_count BIGINT NOT NULL, deleted_until BIGINT NOT NULL, first_observed BIGINT NOT NULL)");
                sql.execute(
                    "CREATE CACHED TABLE IF NOT EXISTS history_resources (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_key VARCHAR(22) NOT NULL, registry_namespace VARCHAR(4096), registry_path VARCHAR(16384), components INTEGER NOT NULL, damage INTEGER NOT NULL, display_name VARCHAR(1048576) NOT NULL, resource_type VARCHAR(16) NOT NULL, icon_key VARCHAR(22))");
                sql.execute("CREATE INDEX IF NOT EXISTS history_resource_key ON history_resources(item_key)");
                sql.execute(
                    "CREATE CACHED TABLE IF NOT EXISTS history_points (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, grid_id BIGINT NOT NULL REFERENCES history_grids(id), observed_at BIGINT NOT NULL, generation BIGINT NOT NULL, kind VARCHAR(16) NOT NULL, item_key VARCHAR(22), resource_id BIGINT REFERENCES history_resources(id), quantity BIGINT NOT NULL, craftable BOOLEAN NOT NULL, input_amount BIGINT NOT NULL, output_amount BIGINT NOT NULL, complete BOOLEAN NOT NULL)");
                sql.execute("CREATE INDEX IF NOT EXISTS history_grid_time ON history_points(grid_id, observed_at, id)");
                sql.execute(
                    "CREATE INDEX IF NOT EXISTS history_item_time ON history_points(grid_id, item_key, observed_at, id)");
                sql.execute(
                    "CREATE INDEX IF NOT EXISTS history_stock_time ON history_points(grid_id, item_key, kind, observed_at, id)");
                sql.execute("CREATE INDEX IF NOT EXISTS history_resource_reference ON history_points(resource_id)");
                sql.execute("CREATE INDEX IF NOT EXISTS history_expiry ON history_points(observed_at, id)");
                sql.execute(
                    "CREATE INDEX IF NOT EXISTS history_coverage ON history_points(grid_id, complete, observed_at)");
            }
            opened.setAutoCommit(false);
            enforceExistingBudgets(opened);
            maintain(opened);
            opened.commit();
            connection = opened;
            return opened;
        } catch (SQLException failure) {
            try {
                opened.rollback();
            } catch (SQLException rollbackFailure) {
                failure.addSuppressed(rollbackFailure);
            }
            try {
                shutdown(opened);
            } catch (SQLException failedShutdown) {
                failure.addSuppressed(failedShutdown);
            }
            throw failure;
        }
    }

    @Override
    public synchronized void append(@NotNull StableKey gridKey, @NotNull List<StorageHistoryPoint> points)
        throws IOException {
        try {
            Connection db = database();
            insertPoints(db, gridKey, points);
            prune(db, gridKey, false);
            maintain(db);
            db.commit();
        } catch (SQLException failure) {
            rollback(failure);
            throw new IOException("Cannot append storage history", failure);
        }
    }

    private void insertPoints(Connection db, StableKey gridKey, List<StorageHistoryPoint> points) throws SQLException {
        ensureGrid(db, gridKey);
        long grid = gridId(db, gridKey);
        int inserted = 0;
        long firstObserved = Long.MAX_VALUE;
        try (PreparedStatement insert = db.prepareStatement(
            "INSERT INTO history_points (grid_id, observed_at, generation, kind, item_key, resource_id, quantity, craftable, input_amount, output_amount, complete) VALUES (?,?,?,?,?,?,?,?,?,?,?)")) {
            for (StorageHistoryPoint point : points) {
                ResourceSnapshot resource = point.resource();
                if (resource != null && resource.itemKey() == null) continue;
                insert.setLong(1, grid);
                insert.setLong(2, point.observedAt());
                insert.setLong(3, point.generation());
                insert.setString(
                    4,
                    point.kind()
                        .name());
                insert.setString(
                    5,
                    resource == null ? null
                        : resource.itemKey()
                            .toString());
                if (resource == null) insert.setNull(6, Types.BIGINT);
                else insert.setLong(6, resourceId(db, resource));
                insert.setLong(7, resource == null ? 0 : resource.quantity());
                insert.setBoolean(8, point.craftable());
                insert.setLong(9, point.input());
                insert.setLong(10, point.output());
                insert.setBoolean(11, point.complete());
                insert.addBatch();
                inserted++;
                firstObserved = Math.min(firstObserved, point.observedAt());
            }
            if (inserted != 0) insert.executeBatch();
        }
        try (PreparedStatement update = db.prepareStatement(
            "UPDATE history_grids SET row_count=row_count+?, first_observed=CASE WHEN first_observed>? THEN ? ELSE first_observed END WHERE grid_key=?")) {
            update.setInt(1, inserted);
            update.setLong(2, firstObserved);
            update.setLong(3, firstObserved);
            update.setString(4, gridKey.toString());
            update.executeUpdate();
        }
    }

    private static void ensureGrid(Connection db, StableKey gridKey) throws SQLException {
        try (PreparedStatement query = db.prepareStatement("SELECT grid_key FROM history_grids WHERE grid_key=?")) {
            query.setString(1, gridKey.toString());
            try (ResultSet rows = query.executeQuery()) {
                if (rows.next()) return;
            }
        }
        try (PreparedStatement insert = db.prepareStatement(
            "INSERT INTO history_grids (grid_key,row_count,deleted_until,first_observed) VALUES (?,0,?,?)")) {
            insert.setString(1, gridKey.toString());
            insert.setLong(2, Long.MIN_VALUE);
            insert.setLong(3, Long.MAX_VALUE);
            insert.executeUpdate();
        }
    }

    private static long gridId(Connection db, StableKey key) throws SQLException {
        try (PreparedStatement query = db.prepareStatement("SELECT id FROM history_grids WHERE grid_key=?")) {
            query.setString(1, key.toString());
            try (ResultSet rows = query.executeQuery()) {
                return rows.next() ? rows.getLong(1) : -1;
            }
        }
    }

    private long cutoff() {
        return System.currentTimeMillis() - TimeUnit.DAYS.toMillis(retentionDays);
    }

    private void prune(Connection db, StableKey gridKey, boolean expire) throws SQLException {
        long count;
        try (PreparedStatement query = db.prepareStatement("SELECT row_count FROM history_grids WHERE grid_key=?")) {
            query.setString(1, gridKey.toString());
            try (ResultSet rows = query.executeQuery()) {
                rows.next();
                count = rows.getLong(1);
            }
        }
        long expiry = cutoff();
        while (true) {
            boolean overCapacity = count > maxRowsPerGrid;
            if (!overCapacity && !expire) return;
            List<Long> ids = new ArrayList<>();
            Set<Long> resources = new HashSet<>();
            long deletedUntil = Long.MIN_VALUE;
            try (PreparedStatement query = db.prepareStatement(
                "SELECT p.id, p.resource_id, p.observed_at FROM history_points p WHERE p.grid_id=?"
                    + (overCapacity ? "" : " AND " + EXPIRED_POINTS)
                    + " ORDER BY p.observed_at, p.id")) {
                query.setLong(1, gridId(db, gridKey));
                if (!overCapacity) {
                    query.setLong(2, expiry);
                    query.setLong(3, expiry);
                }
                query.setMaxRows((int) Math.min(1000, count > maxRowsPerGrid ? count - maxRowsPerGrid : 1000));
                try (ResultSet rows = query.executeQuery()) {
                    while (rows.next()) {
                        ids.add(rows.getLong("id"));
                        long resource = rows.getLong("resource_id");
                        if (!rows.wasNull()) resources.add(resource);
                        deletedUntil = Math.max(deletedUntil, rows.getLong("observed_at"));
                    }
                }
            }
            if (ids.isEmpty()) return;
            try (PreparedStatement delete = db.prepareStatement("DELETE FROM history_points WHERE id=?")) {
                for (long id : ids) {
                    delete.setLong(1, id);
                    delete.addBatch();
                }
                delete.executeBatch();
            }
            try (PreparedStatement delete = db.prepareStatement(
                "DELETE FROM history_resources WHERE id=? AND NOT EXISTS (SELECT 1 FROM history_points WHERE resource_id=?)")) {
                for (long id : resources) {
                    delete.setLong(1, id);
                    delete.setLong(2, id);
                    delete.addBatch();
                }
                if (!resources.isEmpty()) delete.executeBatch();
            }
            count -= ids.size();
            try (PreparedStatement update = db.prepareStatement(
                "UPDATE history_grids SET row_count=?, deleted_until=CASE WHEN deleted_until<? THEN ? ELSE deleted_until END WHERE grid_key=?")) {
                update.setLong(1, count);
                update.setLong(2, deletedUntil);
                update.setLong(3, deletedUntil);
                update.setString(4, gridKey.toString());
                update.executeUpdate();
            }
            // Time retention progresses in bounded chunks; the per-grid row cap is enforced before commit.
            if (!overCapacity) return;
        }
    }

    private void maintain(Connection db) throws SQLException {
        long now = System.currentTimeMillis();
        if (now < nextMaintenance) return;
        nextMaintenance = now + MAINTENANCE_INTERVAL_MILLIS;
        StableKey expired = null;
        try (PreparedStatement query = db.prepareStatement(
            "SELECT g.grid_key FROM history_points p JOIN history_grids g ON p.grid_id=g.id WHERE " + EXPIRED_POINTS
                + " ORDER BY p.observed_at, p.id")) {
            query.setLong(1, cutoff());
            query.setLong(2, cutoff());
            query.setMaxRows(1);
            try (ResultSet rows = query.executeQuery()) {
                if (rows.next()) expired = StableKey.parse(rows.getString(1));
            }
        }
        if (expired != null) prune(db, expired, true);
    }

    private void enforceExistingBudgets(Connection db) throws SQLException {
        while (true) {
            StableKey overBudget = null;
            try (
                PreparedStatement query = db.prepareStatement("SELECT grid_key FROM history_grids WHERE row_count>?")) {
                query.setInt(1, maxRowsPerGrid);
                query.setMaxRows(1);
                try (ResultSet rows = query.executeQuery()) {
                    if (rows.next()) overBudget = StableKey.parse(rows.getString(1));
                }
            }
            if (overBudget == null) return;
            prune(db, overBudget, false);
        }
    }

    private long resourceId(Connection db, ResourceSnapshot resource) throws SQLException {
        try (PreparedStatement find = db.prepareStatement("SELECT * FROM history_resources WHERE item_key=?")) {
            find.setString(
                1,
                resource.itemKey()
                    .toString());
            try (ResultSet rows = find.executeQuery()) {
                while (rows.next()) {
                    if (readResource(rows, resource.quantity()).equals(resource)) return rows.getLong("id");
                }
            }
        }
        try (PreparedStatement insert = db.prepareStatement(
            "INSERT INTO history_resources (item_key, registry_namespace, registry_path, components, damage, display_name, resource_type, icon_key) VALUES (?,?,?,?,?,?,?,?)",
            Statement.RETURN_GENERATED_KEYS)) {
            insert.setString(
                1,
                resource.itemKey()
                    .toString());
            insert.setString(2, resource.registryNamespace());
            insert.setString(3, resource.registryPath());
            insert.setInt(4, resource.componentCount());
            insert.setInt(5, resource.damage());
            insert.setString(6, resource.displayName());
            insert.setString(
                7,
                resource.resourceType()
                    .name());
            insert.setString(
                8,
                resource.iconBaseKey() == null ? null
                    : resource.iconBaseKey()
                        .toString());
            insert.executeUpdate();
            try (ResultSet keys = insert.getGeneratedKeys()) {
                keys.next();
                return keys.getLong(1);
            }
        }
    }

    @Override
    public synchronized @NotNull StorageHistory read(@NotNull StableKey gridKey, @Nullable StableKey itemKey,
        long fromMillis, int limit) throws IOException {
        if (limit < 1 || limit > 10000)
            throw new IllegalArgumentException("History query limit must be between 1 and 10000");
        try {
            Connection db = database();
            List<StorageHistoryPoint> points = new ArrayList<>();
            boolean complete = true;
            boolean retired = false;
            long expiry = cutoff();
            try (PreparedStatement query = db
                .prepareStatement("SELECT deleted_until, first_observed FROM history_grids WHERE grid_key=?")) {
                query.setString(1, gridKey.toString());
                try (ResultSet rows = query.executeQuery()) {
                    if (rows.next()) {
                        retired = rows.getLong(1) != Long.MIN_VALUE && fromMillis <= rows.getLong(1)
                            || fromMillis < expiry && rows.getLong(2) < expiry;
                        complete = !retired;
                    }
                }
            }
            complete &= !retired;
            complete &= !hasIncomplete(db, gridKey, itemKey, Math.max(fromMillis, expiry));
            List<QueryPoint> selected;
            if (itemKey == null) {
                selected = queryPoints(db, gridKey, null, false, Math.max(fromMillis, expiry), limit);
            } else {
                selected = queryPoints(db, gridKey, itemKey, false, Math.max(fromMillis, expiry), limit);
                selected.addAll(queryPoints(db, gridKey, null, true, Math.max(fromMillis, expiry), limit));
                selected.sort((left, right) -> {
                    int time = Long.compare(right.point.observedAt(), left.point.observedAt());
                    return time == 0 ? Long.compare(right.id, left.id) : time;
                });
            }
            boolean truncated = retired || selected.size() > limit;
            for (int index = 0; index < Math.min(limit, selected.size()); index++)
                points.add(selected.get(index).point);
            Collections.reverse(points);
            StorageHistoryPoint baseline = null;
            if (itemKey != null) {
                long boundary = points.isEmpty() ? Math.max(fromMillis, expiry)
                    : points.get(0)
                        .observedAt();
                QueryPoint anchor = queryBaseline(db, gridKey, itemKey, boundary);
                if (anchor != null) {
                    boolean included = false;
                    for (int index = 0; index < Math.min(limit, selected.size()); index++)
                        included |= selected.get(index).id == anchor.id;
                    if (!included) baseline = anchor.point;
                }
            }
            db.commit();
            return new StorageHistory(points, complete, truncated, baseline);
        } catch (SQLException failure) {
            rollback(failure);
            throw new IOException("Cannot query storage history", failure);
        }
    }

    private static List<QueryPoint> queryPoints(Connection db, StableKey gridKey, @Nullable StableKey itemKey,
        boolean markersOnly, long fromMillis, int limit) throws SQLException {
        List<QueryPoint> result = new ArrayList<>();
        String filter = itemKey != null ? " AND p.item_key=?" : markersOnly ? " AND p.item_key IS NULL" : "";
        try (PreparedStatement query = db.prepareStatement(
            "SELECT p.*, r.registry_namespace, r.registry_path, r.components, r.damage, r.display_name, r.resource_type, r.icon_key FROM history_points p LEFT JOIN history_resources r ON p.resource_id=r.id WHERE p.grid_id=? AND p.observed_at>=?"
                + filter
                + " ORDER BY p.observed_at DESC, p.id DESC")) {
            query.setLong(1, gridId(db, gridKey));
            query.setLong(2, fromMillis);
            if (itemKey != null) query.setString(3, itemKey.toString());
            query.setMaxRows(limit + 1);
            try (ResultSet rows = query.executeQuery()) {
                while (rows.next()) {
                    ResourceSnapshot resource = rows.getString("item_key") == null ? null
                        : readResource(rows, rows.getLong("quantity"));
                    StorageHistoryPoint point = new StorageHistoryPoint(
                        rows.getLong("observed_at"),
                        rows.getLong("generation"),
                        StorageHistoryPoint.Kind.valueOf(rows.getString("kind")),
                        resource,
                        rows.getBoolean("craftable"),
                        rows.getLong("input_amount"),
                        rows.getLong("output_amount"),
                        rows.getBoolean("complete"));
                    result.add(new QueryPoint(rows.getLong("id"), point));
                }
            }
        }
        return result;
    }

    private static boolean hasIncomplete(Connection db, StableKey gridKey, @Nullable StableKey itemKey, long fromMillis)
        throws SQLException {
        String filter = itemKey == null ? "" : " AND (item_key=? OR item_key IS NULL)";
        try (PreparedStatement query = db.prepareStatement(
            "SELECT id FROM history_points WHERE grid_id=? AND complete=FALSE AND observed_at>=?" + filter)) {
            query.setLong(1, gridId(db, gridKey));
            query.setLong(2, fromMillis);
            if (itemKey != null) query.setString(3, itemKey.toString());
            query.setMaxRows(1);
            try (ResultSet rows = query.executeQuery()) {
                return rows.next();
            }
        }
    }

    private static @Nullable QueryPoint queryBaseline(Connection db, StableKey gridKey, StableKey itemKey,
        long boundary) throws SQLException {
        try (PreparedStatement query = db.prepareStatement(
            "SELECT p.*, r.registry_namespace, r.registry_path, r.components, r.damage, r.display_name, r.resource_type, r.icon_key FROM history_points p JOIN history_resources r ON p.resource_id=r.id WHERE p.grid_id=? AND p.item_key=? AND p.kind='STOCK' AND p.observed_at<=? ORDER BY p.observed_at DESC, p.id DESC")) {
            query.setLong(1, gridId(db, gridKey));
            query.setString(2, itemKey.toString());
            query.setLong(3, boundary);
            query.setMaxRows(1);
            try (ResultSet rows = query.executeQuery()) {
                if (!rows.next()) return null;
                ResourceSnapshot resource = readResource(rows, rows.getLong("quantity"));
                return new QueryPoint(
                    rows.getLong("id"),
                    new StorageHistoryPoint(
                        rows.getLong("observed_at"),
                        rows.getLong("generation"),
                        StorageHistoryPoint.Kind.STOCK,
                        resource,
                        rows.getBoolean("craftable"),
                        rows.getLong("input_amount"),
                        rows.getLong("output_amount"),
                        rows.getBoolean("complete")));
            }
        }
    }

    private static final class QueryPoint {

        private final long id;
        private final StorageHistoryPoint point;

        private QueryPoint(long id, StorageHistoryPoint point) {
            this.id = id;
            this.point = point;
        }
    }

    private static ResourceSnapshot readResource(ResultSet row, long quantity) throws SQLException {
        String icon = row.getString("icon_key");
        return new ResourceSnapshot(
            row.getString("registry_namespace"),
            row.getString("registry_path"),
            row.getInt("components"),
            row.getInt("damage"),
            row.getString("display_name"),
            ResourceType.valueOf(row.getString("resource_type")),
            quantity,
            StableKey.parse(row.getString("item_key")),
            icon == null ? null : StableKey.parse(icon));
    }

    private void rollback(SQLException failure) {
        try {
            if (connection != null) connection.rollback();
        } catch (SQLException rollbackFailure) {
            failure.addSuppressed(rollbackFailure);
        }
    }

    @Override
    public synchronized void close() throws IOException {
        if (closed) return;
        closed = true;
        if (connection == null) return;
        try {
            shutdown(connection);
        } catch (SQLException failure) {
            throw new IOException("Cannot close storage history", failure);
        } finally {
            connection = null;
        }
    }

    private void shutdown(Connection db) throws SQLException {
        SQLException failure = null;
        boolean stopped = false;
        try (Statement sql = db.createStatement()) {
            sql.execute("SHUTDOWN");
            stopped = true;
        } catch (SQLException failedShutdown) {
            failure = failedShutdown;
        }
        try {
            db.close();
        } catch (SQLException failedClose) {
            if (failure == null) failure = failedClose;
            else failure.addSuppressed(failedClose);
        }
        // A failed SHUTDOWN keeps the path reserved until process exit: another owner must not share that engine.
        if (stopped) releaseOwnership();
        if (failure != null) throw failure;
    }

    private void releaseOwnership() {
        if (ownedPath == null) return;
        OPEN_DATABASES.remove(ownedPath);
        ownedPath = null;
    }
}
