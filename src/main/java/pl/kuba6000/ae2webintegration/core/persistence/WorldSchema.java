package pl.kuba6000.ae2webintegration.core.persistence;

import java.io.IOException;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import org.jetbrains.annotations.NotNull;

/** The current world schema; future versions require explicit, separately implemented migration steps. */
final class WorldSchema {

    private WorldSchema() {}

    static void initialize(@NotNull Connection db) throws SQLException, IOException {
        boolean schema = false;
        boolean existing = false;
        try (ResultSet tables = db.getMetaData()
            .getTables(null, "PUBLIC", null, new String[] { "TABLE" })) {
            while (tables.next()) {
                existing = true;
                schema |= tables.getString("TABLE_NAME")
                    .equals("WORLD_SCHEMA");
            }
        }
        if (schema) {
            try (Statement sql = db.createStatement();
                ResultSet rows = sql.executeQuery("SELECT version FROM world_schema WHERE singleton = 1")) {
                if (!rows.next() || rows.getInt(1) != 2)
                    throw new IOException("Unsupported world database schema version");
            }
            return;
        }
        if (existing) throw new IOException("World database schema version is missing");
        try (Statement sql = db.createStatement()) {
            sql.execute("SET DATABASE TRANSACTION CONTROL MVCC");
            sql.execute("SET FILES WRITE DELAY FALSE");
            sql.execute("SET FILES CACHE SIZE 16384");
            sql.execute("SET FILES LOG SIZE 16");
            sql.execute("SET FILES DEFRAG 25");
            sql.execute("""
                CREATE CACHED TABLE grids (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    grid_key VARCHAR(22) NOT NULL UNIQUE,
                    row_count BIGINT NOT NULL,
                    deleted_until BIGINT NOT NULL,
                    first_observed BIGINT NOT NULL,
                    retention_days INTEGER NOT NULL,
                    name VARCHAR(128) NOT NULL,
                    crafting_tracked BOOLEAN NOT NULL,
                    stock_tracked BOOLEAN NOT NULL,
                    flow_tracked BOOLEAN NOT NULL,
                    stock_seconds INTEGER NOT NULL,
                    flow_seconds INTEGER NOT NULL
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE history_resources (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    item_key VARCHAR(22) NOT NULL UNIQUE,
                    registry_namespace VARCHAR(4096),
                    registry_path VARCHAR(16384),
                    components INTEGER NOT NULL,
                    damage INTEGER NOT NULL,
                    display_name VARCHAR(1048576) NOT NULL,
                    resource_type VARCHAR(16) NOT NULL,
                    base_key VARCHAR(22)
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE grid_controllers (
                    grid_id BIGINT NOT NULL REFERENCES grids(id),
                    dimension_id VARCHAR(4096) NOT NULL,
                    x INTEGER NOT NULL, y INTEGER NOT NULL, z INTEGER NOT NULL,
                    PRIMARY KEY (dimension_id, x, y, z)
                )
                """);
            sql.execute("CREATE INDEX grid_controllers_grid ON grid_controllers(grid_id)");
            sql.execute("CREATE SEQUENCE history_event_ids AS BIGINT START WITH 1");
            sql.execute("""
                CREATE CACHED TABLE history_stock (
                    id BIGINT PRIMARY KEY,
                    grid_id BIGINT NOT NULL REFERENCES grids(id),
                    observed_at BIGINT NOT NULL,
                    generation BIGINT NOT NULL,
                    resource_id BIGINT NOT NULL REFERENCES history_resources(id),
                    quantity BIGINT NOT NULL
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE history_flow (
                    id BIGINT PRIMARY KEY,
                    grid_id BIGINT NOT NULL REFERENCES grids(id),
                    observed_at BIGINT NOT NULL,
                    generation BIGINT NOT NULL,
                    resource_id BIGINT NOT NULL REFERENCES history_resources(id),
                    input_amount BIGINT NOT NULL,
                    output_amount BIGINT NOT NULL,
                    flow_from BIGINT NOT NULL
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE history_coverage (
                    id BIGINT PRIMARY KEY,
                    grid_id BIGINT NOT NULL REFERENCES grids(id),
                    observed_at BIGINT NOT NULL,
                    generation BIGINT NOT NULL,
                    kind VARCHAR(16) NOT NULL CHECK (kind IN ('GAP', 'OBSERVATION', 'FLOW_OBSERVATION')),
                    flow_from BIGINT
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE resource_pins (
                    pin_key VARCHAR(22) PRIMARY KEY,
                    owner VARCHAR(36) NOT NULL,
                    grid_id BIGINT NOT NULL REFERENCES grids(id),
                    resource_id BIGINT NOT NULL REFERENCES history_resources(id),
                    terminal_order INTEGER CHECK (terminal_order >= 0),
                    home_order INTEGER CHECK (home_order >= 0),
                    show_stock BOOLEAN NOT NULL, show_flow BOOLEAN NOT NULL, show_chart BOOLEAN NOT NULL,
                    series_stock BOOLEAN NOT NULL, series_input BOOLEAN NOT NULL,
                    series_output BOOLEAN NOT NULL, series_net BOOLEAN NOT NULL,
                    range_millis BIGINT NOT NULL,
                    show_recent_flow BOOLEAN NOT NULL,
                    flow_range_millis BIGINT NOT NULL,
                    UNIQUE (owner, grid_id, resource_id),
                    CHECK (terminal_order IS NOT NULL OR home_order IS NOT NULL)
                )
                """);
            sql.execute("CREATE INDEX resource_pins_resource ON resource_pins(resource_id)");
            for (String name : new String[] { "history_stock", "history_flow", "history_coverage" }) {
                sql.execute("CREATE INDEX " + name + "_grid_time ON " + name + "(grid_id, observed_at, id)");
                sql.execute("CREATE INDEX " + name + "_expiry ON " + name + "(observed_at, id)");
                if (!name.equals("history_coverage")) {
                    sql.execute(
                        "CREATE INDEX " + name + "_item_time ON " + name + "(grid_id, resource_id, observed_at, id)");
                    sql.execute("CREATE INDEX " + name + "_resource ON " + name + "(resource_id)");
                }
            }
            sql.execute("CREATE INDEX history_coverage_gap ON history_coverage(grid_id, kind, observed_at, id)");
            sql.execute("""
                CREATE TABLE world_schema (
                    singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
                    version INTEGER NOT NULL,
                    identities_imported BOOLEAN NOT NULL
                )
                """);
            sql.execute("INSERT INTO world_schema VALUES (1, 2, FALSE)");
        }
    }
}
