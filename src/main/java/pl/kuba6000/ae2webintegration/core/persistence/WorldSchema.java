package pl.kuba6000.ae2webintegration.core.persistence;

import java.io.IOException;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Arrays;
import java.util.HashSet;
import java.util.Set;

import org.jetbrains.annotations.NotNull;

/** The current world schema; future versions require explicit, separately implemented migration steps. */
final class WorldSchema {

    private static final int VERSION = 5;
    private static final String[] OWNED_TABLES = { "RESOURCE_PINS", "HISTORY_STOCK", "HISTORY_FLOW", "HISTORY_COVERAGE",
        "HISTORY_MEASUREMENTS", "GRID_CONTROLLERS", "HISTORY_RESOURCES", "GRIDS" };

    private WorldSchema() {}

    static void initialize(@NotNull Connection db) throws SQLException, IOException {
        Set<String> existing = new HashSet<>();
        try (ResultSet tables = db.getMetaData()
            .getTables(null, "PUBLIC", null, null)) {
            while (tables.next()) {
                existing.add(tables.getString("TABLE_NAME"));
            }
        }
        if (existing.contains("WORLD_SCHEMA")) {
            try (Statement sql = db.createStatement();
                ResultSet rows = sql.executeQuery("SELECT version FROM world_schema WHERE singleton = 1")) {
                if (!rows.next() || rows.getInt(1) != VERSION || rows.next())
                    throw new IOException("Unsupported world database schema version");
            }
            try (Statement sql = db.createStatement();
                ResultSet rows = sql.executeQuery("SELECT initialized, identities_imported FROM world_schema")) {
                if (!rows.next()) throw new IOException("World database initialization marker is missing");
                boolean initialized = rows.getBoolean(1);
                boolean imported = rows.getBoolean(2);
                if (rows.next()) throw new IOException("Invalid world database initialization marker");
                if (initialized) return;
                if (imported) throw new IOException("Incomplete world database already contains imported data");
            }
            resetIncompleteBootstrap(db, existing);
        } else {
            if (!existing.isEmpty()) throw new IOException("World database schema version is missing");
            try (Statement sql = db.createStatement();
                ResultSet sequences = sql
                    .executeQuery("SELECT 1 FROM INFORMATION_SCHEMA.SEQUENCES WHERE SEQUENCE_SCHEMA = 'PUBLIC'")) {
                if (sequences.next()) throw new IOException("World database schema version is missing");
            }
            try (Statement sql = db.createStatement()) {
                // HSQL logs this complete DDL, including its row, as one initialization marker.
                sql.execute("""
                    CREATE TABLE world_schema (
                        singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
                        version INTEGER NOT NULL,
                        identities_imported BOOLEAN NOT NULL,
                        initialized BOOLEAN NOT NULL
                    ) AS (VALUES (1, 5, FALSE, FALSE)) WITH DATA
                    """);
            }
        }
        try (Statement sql = db.createStatement()) {
            sql.execute("SET DATABASE TRANSACTION CONTROL MVCC");
            sql.execute("SET FILES WRITE DELAY FALSE");
            sql.execute("SET FILES CACHE SIZE 16384");
            sql.execute("SET FILES LOG SIZE 16");
            sql.execute("SET FILES DEFRAG 25");
            sql.execute("""
                CREATE CACHED TABLE grids (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    grid_key VARCHAR(22) NOT NULL UNIQUE,
                    row_count BIGINT NOT NULL,
                    deleted_until BIGINT NOT NULL,
                    first_observed BIGINT NOT NULL,
                    retention_days INTEGER NOT NULL,
                    name VARCHAR(128) NOT NULL,
                    crafting_tracked BOOLEAN NOT NULL,
                    machine_crafting_tracked BOOLEAN NOT NULL,
                    stock_tracked BOOLEAN NOT NULL,
                    flow_tracked BOOLEAN NOT NULL,
                    stock_seconds INTEGER NOT NULL,
                    flow_seconds INTEGER NOT NULL
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE history_resources (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    item_key VARCHAR(22) NOT NULL UNIQUE,
                    registry_namespace VARCHAR(4096),
                    registry_path VARCHAR(16384),
                    components INTEGER NOT NULL,
                    damage INTEGER NOT NULL,
                    display_name VARCHAR(1048576) NOT NULL,
                    resource_type VARCHAR(16) NOT NULL,
                    base_key VARCHAR(22)
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE grid_controllers (
                    grid_id BIGINT NOT NULL REFERENCES grids(id),
                    dimension_id VARCHAR(4096) NOT NULL,
                    x INTEGER NOT NULL, y INTEGER NOT NULL, z INTEGER NOT NULL,
                    PRIMARY KEY (dimension_id, x, y, z)
                )
                """);
            sql.execute("CREATE SEQUENCE history_event_ids AS BIGINT START WITH 1");
            sql.execute("""
                CREATE CACHED TABLE history_measurements (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    grid_id BIGINT NOT NULL REFERENCES grids(id),
                    observed_at BIGINT NOT NULL,
                    generation BIGINT NOT NULL,
                    flow_from BIGINT
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE history_stock (
                    id BIGINT PRIMARY KEY,
                    measurement_id BIGINT NOT NULL REFERENCES history_measurements(id),
                    resource_id BIGINT NOT NULL REFERENCES history_resources(id),
                    quantity BIGINT NOT NULL
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE history_flow (
                    id BIGINT PRIMARY KEY,
                    measurement_id BIGINT NOT NULL REFERENCES history_measurements(id),
                    resource_id BIGINT NOT NULL REFERENCES history_resources(id),
                    input_amount BIGINT NOT NULL,
                    output_amount BIGINT NOT NULL,
                    input_operations BIGINT NOT NULL,
                    output_operations BIGINT NOT NULL
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE history_coverage (
                    id BIGINT PRIMARY KEY,
                    measurement_id BIGINT NOT NULL REFERENCES history_measurements(id),
                    kind VARCHAR(16) NOT NULL CHECK (kind IN ('GAP', 'OBSERVATION', 'FLOW_OBSERVATION'))
                )
                """);
            sql.execute("""
                CREATE CACHED TABLE resource_pins (
                    pin_key VARCHAR(22) PRIMARY KEY,
                    owner VARCHAR(36) NOT NULL,
                    grid_id BIGINT NOT NULL REFERENCES grids(id),
                    resource_id BIGINT NOT NULL REFERENCES history_resources(id),
                    terminal_order INTEGER CHECK (terminal_order >= 0),
                    home_order INTEGER CHECK (home_order >= 0),
                    show_stock BOOLEAN NOT NULL, show_flow BOOLEAN NOT NULL, show_chart BOOLEAN NOT NULL,
                    series_stock BOOLEAN NOT NULL, series_input BOOLEAN NOT NULL,
                    series_output BOOLEAN NOT NULL, series_net BOOLEAN NOT NULL,
                    range_millis BIGINT NOT NULL,
                    show_recent_flow BOOLEAN NOT NULL,
                    flow_range_millis BIGINT NOT NULL,
                    UNIQUE (owner, grid_id, resource_id),
                    CHECK (terminal_order IS NOT NULL OR home_order IS NOT NULL)
                )
                """);
            sql.execute(
                "CREATE INDEX history_measurements_grid_time ON history_measurements(grid_id, observed_at, id)");
            for (String name : new String[] { "history_stock", "history_flow", "history_coverage" }) {
                String field = name.equals("history_coverage") ? "kind" : "resource_id";
                sql.execute(
                    "CREATE INDEX " + name + "_measurement_item ON " + name + "(measurement_id, " + field + ", id)");
            }
            sql.execute("UPDATE world_schema SET initialized = TRUE WHERE singleton = 1");
        }
    }

    /** Only a recognized, empty initialization may be rebuilt; published or unknown data is never reset. */
    private static void resetIncompleteBootstrap(Connection db, Set<String> existing) throws SQLException, IOException {
        Set<String> owned = new HashSet<>(Arrays.asList(OWNED_TABLES));
        owned.add("WORLD_SCHEMA");
        if (!owned.containsAll(existing)) throw new IOException("Incomplete world database contains unknown objects");
        try (Statement sql = db.createStatement()) {
            sql.setMaxRows(1);
            for (String table : OWNED_TABLES) {
                if (!existing.contains(table)) continue;
                try (ResultSet rows = sql.executeQuery("SELECT 1 FROM " + table)) {
                    if (rows.next()) throw new IOException("Incomplete world database contains application data");
                }
            }
            try (ResultSet triggers = sql
                .executeQuery("SELECT 1 FROM INFORMATION_SCHEMA.TRIGGERS WHERE TRIGGER_SCHEMA = 'PUBLIC'")) {
                if (triggers.next()) throw new IOException("Incomplete world database contains unknown triggers");
            }
        }
        boolean sequence = false;
        try (Statement sql = db.createStatement();
            ResultSet sequences = sql.executeQuery(
                "SELECT SEQUENCE_NAME FROM INFORMATION_SCHEMA.SEQUENCES WHERE SEQUENCE_SCHEMA = 'PUBLIC'")) {
            while (sequences.next()) {
                if (!sequences.getString(1)
                    .equals("HISTORY_EVENT_IDS"))
                    throw new IOException("Incomplete world database contains unknown sequences");
                sequence = true;
            }
        }
        try (Statement sql = db.createStatement()) {
            for (String table : OWNED_TABLES) {
                if (existing.contains(table)) sql.execute("DROP TABLE " + table);
            }
            if (sequence) sql.execute("DROP SEQUENCE history_event_ids");
        }
    }
}
